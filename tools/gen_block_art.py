#!/usr/bin/env python3
"""Draws the textures for blocks Crafti Survival Edition adds and writes block_art.cpp.

All art is original: Ancient Debris, the chest and the smithing table.
(Emerald ore, wool, the emerald block, saplings and beds use the textures in
Crafti's bundled PureBDcraft atlas instead.) Usage: python3 tools/gen_block_art.py (from the repository root).
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_gui_art import Img, KEY, c_array  # noqa: E402


def debris_side():
    rnd = random.Random(33)
    img = Img(16, 16)
    for y in range(16):
        for x in range(16):
            base = (74, 52, 46)
            # dark curved bands, like layers of old scorched metal
            band = (x * 3 + (y - 8) ** 2 // 3) % 7
            if band in (0, 1):
                base = (40, 27, 24)
            if band == 3:
                base = (118, 88, 72)
            v = rnd.randint(-8, 8)
            img.set(x, y, tuple(max(0, min(255, c + v)) for c in base))
    # a few bright flecks
    for _ in range(5):
        img.set(rnd.randint(1, 14), rnd.randint(1, 14), (150, 118, 96))
    return img


def debris_top():
    rnd = random.Random(34)
    img = Img(16, 16)
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, y - 7.5
            ring = int((dx * dx + dy * dy) ** 0.5) % 3
            base = (66, 46, 40) if ring else (96, 70, 60)
            v = rnd.randint(-6, 6)
            img.set(x, y, tuple(max(0, min(255, c + v)) for c in base))
    return img


def planks(rnd, dark=(96, 62, 30), mid=(146, 98, 52), light=(176, 124, 70)):
    """Horizontal boards with grain, used by the chest."""
    img = Img(16, 16)
    for y in range(16):
        for x in range(16):
            c = mid
            if y % 5 == 4:
                c = dark                      # gap between boards
            elif (x * 7 + y * 3) % 11 == 0:
                c = light                     # grain highlight
            v = rnd.randint(-7, 7)
            img.set(x, y, tuple(max(0, min(255, k + v)) for k in c))
    return img


def frame(img, color):
    for i in range(16):
        img.set(i, 0, color); img.set(i, 15, color)
        img.set(0, i, color); img.set(15, i, color)


def chest_side():
    img = planks(random.Random(51))
    frame(img, (70, 44, 20))
    for x in range(1, 15):
        img.set(x, 5, (62, 38, 18))
    return img


def chest_front():
    img = chest_side()
    # an iron latch across the lid line
    for y in range(4, 9):
        for x in range(7, 9 + 1):
            img.set(x, y, (196, 196, 204) if (x, y) != (8, 6) else (60, 60, 70))
    img.set(7, 4, (120, 120, 130)); img.set(9, 4, (120, 120, 130))
    img.set(7, 8, (120, 120, 130)); img.set(9, 8, (120, 120, 130))
    return img


def chest_top():
    img = planks(random.Random(52))
    frame(img, (70, 44, 20))
    return img


def smithing_top():
    rnd = random.Random(61)
    img = Img(16, 16)
    for y in range(16):
        for x in range(16):
            v = rnd.randint(-10, 10)
            img.set(x, y, (58 + v, 58 + v, 66 + v))      # dark stone slab
    for i in range(16):
        img.set(i, 0, (30, 30, 36)); img.set(i, 15, (30, 30, 36))
        img.set(0, i, (30, 30, 36)); img.set(15, i, (30, 30, 36))
    for x in range(3, 13):                               # an iron plate in the middle
        for y in range(5, 11):
            img.set(x, y, (178, 180, 190) if (x + y) % 5 else (210, 212, 220))
    return img


def smithing_side():
    rnd = random.Random(62)
    img = planks(rnd, dark=(46, 30, 20), mid=(84, 56, 36), light=(104, 72, 46))
    for x in range(16):                                  # stone top edge and an iron band
        img.set(x, 0, (58, 58, 66)); img.set(x, 1, (72, 72, 80))
        img.set(x, 7, (150, 152, 162)); img.set(x, 8, (110, 112, 122))
    return img


def smithing_front():
    img = smithing_side()
    # a small hammer hanging on the front
    for y in range(9, 15):
        img.set(8, y, (150, 104, 60))
    for x in range(6, 11):
        img.set(x, 9, (196, 198, 208)); img.set(x, 10, (140, 142, 152))
    return img


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    preview = os.path.join(root, 'tools', 'preview')
    os.makedirs(preview, exist_ok=True)
    out = ['// Generated by tools/gen_block_art.py - do not edit by hand.',
           '// All art is original to Crafti Survival Edition.',
           '#include "block_art.h"', '']
    for name, img in (('art_debris_side', debris_side()), ('art_debris_top', debris_top()),
                      ('art_chest_top', chest_top()), ('art_chest_side', chest_side()), ('art_chest_front', chest_front()),
                      ('art_smithing_top', smithing_top()), ('art_smithing_side', smithing_side()),
                      ('art_smithing_front', smithing_front())):
        out.append(c_array(name, img.to565()))
        out.append('const TEXTURE %s = { %d, %d, true, 0x%04X, %s_data };' % (name, img.w, img.h, KEY, name))
        out.append('')
        img.save_preview(os.path.join(preview, name + '.png'), scale=8)
    with open(os.path.join(root, 'block_art.cpp'), 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
